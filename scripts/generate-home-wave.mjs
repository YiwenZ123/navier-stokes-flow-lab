// Rebuild the homepage replay with the exact solver and time advances used by waves.html.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { createWaveSolver } from '../dist/wave-solver.js';

const options = {
  scenario: 'dam-break', amplitude: 0.12, resolution: 120,
  obstacle: { shape: 'square', size: 0.7, centerX: 2.75, bottomY: 0 }
};
const solver = createWaveSolver(options);
const solverSha256 = createHash('sha256').update(await readFile(new URL('../dist/wave-solver.js', import.meta.url))).digest('hex');
const frames = [], times = [];
function capture() {
  const bits = Buffer.alloc(Math.ceil(solver.state.mask.length / 8));
  solver.state.mask.forEach((value, index) => {
    assert(value === 0 || value === 1);
    assert(!(value && solver.state.solid[index]), 'Water cannot occupy a solid cell');
    if (value) bits[index >> 3] |= 1 << (index & 7);
  });
  frames.push(bits.toString('base64'));
  times.push(Number(solver.state.time.toFixed(9)));
}
capture();
for (let step = 1; step <= 360; step++) {
  solver.step(Math.min(1 / 60, 6 - solver.state.time));
  assert(!solver.state.failed, solver.state.message);
  for (const field of [solver.state.u, solver.state.v, solver.state.pressure]) assert(field.every(Number.isFinite));
  capture();
}
assert(Math.abs(solver.state.time - 6) < 1e-8);
const metadata = {
  options, nx: solver.nx, ny: solver.ny, width: solver.width, height: solver.height,
  h: solver.h, duration: 6, fps: 60, integrationInterval: 1 / 60,
  sampleEvery: 1, solverSha256, encoding: 'base64-lsb-first-liquid-mask', times
};
const source = '// Generated by scripts/generate-home-wave.mjs. Actual MAC solver results; no decorative fluid approximation.\n'
  + `export const metadata = ${JSON.stringify(metadata)};\n`
  + `export const frames = [\n${frames.map(frame => JSON.stringify(frame)).join(',\n')}\n];\n`;
await writeFile(new URL('../dist/assets/home-wave-data.js', import.meta.url), source);
console.log(JSON.stringify({ frames: frames.length, bytes: Buffer.byteLength(source), solverSha256, duration: solver.state.time, options }));
